#!/usr/bin/env python3
"""Compute a documented baseline of Natural Earth country areas by CONTINENT.

This is deliberately a country-classification baseline, not a claim that
political country assignments are a perfect natural-continent boundary.
No image or map is generated by this script.
"""
from __future__ import annotations

import json
import os
import sys
import tempfile
import zipfile
from datetime import datetime, timezone
from pathlib import Path
from urllib.request import urlopen

import geopandas as gpd
import pandas as pd
import pyproj
from shapely.geometry import Polygon, MultiPolygon
from shapely import make_valid
from shapely.ops import unary_union

SOURCE_URL = (
    "https://naturalearth.s3.amazonaws.com/10m_cultural/"
    "ne_10m_admin_0_countries.zip"
)
OUTPUT_DIR = Path(os.environ.get("OUTPUT_DIR", "output/geography"))
AREA_FIELDS = ("CONTINENT", "NAME", "ISO_A3")


def main() -> int:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="natural-earth-") as tmp:
        archive = Path(tmp) / "countries.zip"
        with urlopen(SOURCE_URL, timeout=60) as response, archive.open("wb") as out:
            out.write(response.read())

        if not zipfile.is_zipfile(archive):
            raise RuntimeError("Natural Earth download is not a valid ZIP archive")

        # GeoPandas reads the shapefile directly from the downloaded archive.
        frame = gpd.read_file(f"zip://{archive}")
        missing = [field for field in AREA_FIELDS if field not in frame.columns]
        if missing:
            raise RuntimeError(f"Required Natural Earth fields missing: {missing}")
        if frame.empty or frame.geometry.isna().any():
            raise RuntimeError("Country dataset is empty or contains null geometry")

        geod = pyproj.Geod(ellps="WGS84")
        rows = []
        repaired_features = []
        for _, feature in frame.iterrows():
            geometry = feature.geometry
            if geometry is None or geometry.is_empty:
                raise RuntimeError(
                    f"Missing or empty geometry for Natural Earth feature: {feature['NAME']}"
                )
            if not geometry.is_valid:
                # Repair source-topology defects, retaining polygonal land only.
                repaired = make_valid(geometry)
                stack = [repaired]
                polygon_parts = []
                while stack:
                    part = stack.pop()
                    if isinstance(part, Polygon):
                        polygon_parts.append(part)
                    elif isinstance(part, MultiPolygon):
                        polygon_parts.extend(list(part.geoms))
                    elif hasattr(part, 'geoms'):
                        stack.extend(list(part.geoms))
                if not polygon_parts:
                    raise RuntimeError(
                        f"Geometry repair produced no polygon for {feature['NAME']}"
                    )
                geometry = unary_union(polygon_parts)
                if geometry.is_empty or not geometry.is_valid:
                    raise RuntimeError(
                        f"Geometry remains invalid after repair: {feature['NAME']}"
                    )
                repaired_features.append(str(feature['NAME']))
            area_m2, _ = geod.geometry_area_perimeter(geometry)
            # The signed result depends on ring orientation; use magnitude.
            area_km2 = abs(float(area_m2)) / 1_000_000.0
            if not (area_km2 > 0):
                raise RuntimeError(
                    f"Non-positive area for Natural Earth feature: {feature['NAME']}"
                )
            rows.append({
                "continent": str(feature["CONTINENT"]).strip(),
                "country_or_area": str(feature["NAME"]).strip(),
                "iso_a3": str(feature["ISO_A3"]).strip(),
                "area_km2": area_km2,
            })

        detail = pd.DataFrame(rows).sort_values(
            ["continent", "country_or_area"], kind="stable"
        )
        if detail["continent"].eq("").any():
            raise RuntimeError("Empty CONTINENT classification found")

        totals = (
            detail.groupby("continent", as_index=False)
            .agg(
                features=("country_or_area", "count"),
                area_km2=("area_km2", "sum"),
            )
            .sort_values("area_km2", ascending=False)
        )
        totals["area_million_km2"] = totals["area_km2"] / 1_000_000.0

        detail_path = OUTPUT_DIR / "country_area_baseline.csv"
        totals_path = OUTPUT_DIR / "continent_area_baseline.csv"
        audit_path = OUTPUT_DIR / "area_audit.json"
        detail.to_csv(detail_path, index=False, float_format="%.3f")
        totals.to_csv(totals_path, index=False, float_format="%.6f")

        audit = {
            "status": "PRELIMINARY_BASELINE_NOT_FINAL_CONTINENT_GEOGRAPHY",
            "source": "Natural Earth Admin 0 Countries 1:10m",
            "source_url": SOURCE_URL,
            "measurement": "Geodesic polygon area on WGS84 ellipsoid via pyproj.Geod",
            "grouping": (
                "Natural Earth CONTINENT field; transcontinental country treatment "
                "inherits dataset classification and is not a natural boundary model"
            ),
            "feature_count": int(len(detail)),
            "continent_groups": int(totals["continent"].nunique()),
            "sum_country_area_km2": round(float(detail["area_km2"].sum()), 3),
            "null_geometry_count": int(frame.geometry.isna().sum()),
            "invalid_geometry_count_in_source": int((~frame.geometry.is_valid).sum()),
            "repaired_geometry_count": len(repaired_features),
            "repaired_geometry_features": repaired_features,
            "created_utc": datetime.now(timezone.utc).isoformat(),
            "python": sys.version.split()[0],
            "geopandas": gpd.__version__,
            "pandas": pd.__version__,
            "pyproj": pyproj.__version__,
            "files": [
                detail_path.name,
                totals_path.name,
                audit_path.name,
            ],
        }
        audit_path.write_text(
            json.dumps(audit, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )

        if len(detail) == 0 or totals.empty or not totals["area_km2"].gt(0).all():
            raise RuntimeError("Area output validation failed")
        if not all(path.exists() and path.stat().st_size > 0
                   for path in (detail_path, totals_path, audit_path)):
            raise RuntimeError("One or more output files are missing or empty")

        print(json.dumps(audit, ensure_ascii=False, indent=2))
        print("\nPreliminary area totals (million km²):")
        print(totals[["continent", "features", "area_million_km2"]].to_string(index=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
