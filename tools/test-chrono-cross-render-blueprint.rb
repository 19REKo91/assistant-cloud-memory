require "yaml"
require "json"

blueprint = YAML.safe_load_file("render.yaml", aliases: false)
abort "Blueprint must define exactly one service" unless blueprint["services"].is_a?(Array) && blueprint["services"].length == 1
service = blueprint["services"].first

checks = {
  "service type" => [service["type"], "web"],
  "service runtime" => [service["runtime"], "docker"],
  "compute plan must remain free" => [service["plan"], "free"],
  "region" => [service["region"], "frankfurt"],
  "Dockerfile path" => [service["dockerfilePath"], "chrono-reader-core/Dockerfile"],
  "Docker context" => [service["dockerContext"], "chrono-reader-core"],
  "health check path" => [service["healthCheckPath"], "/health"],
  "automatic deployment must be off" => [service["autoDeployTrigger"], "off"]
}
checks.each do |label, (actual, expected)|
  abort "#{label} mismatch" unless actual == expected
end

env = service["envVars"]
abort "environment variables must be a list" unless env.is_a?(Array)
by_key = env.to_h { |entry| [entry["key"], entry] }
abort "NODE_ENV must be production" unless by_key.dig("NODE_ENV", "value") == "production"
secret = by_key["CHRONO_READER_BRIDGE_TOKEN"]
abort "secret must prompt for a dashboard value" unless secret && secret["sync"] == false
abort "secret must not be hard-coded or generated by committed source" if secret.key?("value") || secret.key?("generateValue")
abort "PORT should be injected by the host platform" if by_key.key?("PORT")
abort "unexpected environment variables in free deployment blueprint" unless (by_key.keys - ["NODE_ENV", "CHRONO_READER_BRIDGE_TOKEN"]).empty?

serialized = JSON.generate(blueprint)
abort "Blueprint must not contain a bearer credential" if serialized.match?(/Bearer\\s+[A-Za-z0-9._-]{20,}/i)
puts "PASS Render Blueprint: free Docker service, Frankfurt region, manual deploy, secret prompt, platform PORT"
